function applyLanguage(lang) {
    localStorage.setItem("lang", lang);

    // existing translation logic...
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (translations[lang] && translations[lang][key]) {
            el.innerText = translations[lang][key];
        }
    });

    // ✅ ADD THIS
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: lang }));
}

window.applyLanguage = (lang) => {
    localStorage.setItem("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (!translations[lang] || !translations[lang][key]) return;

        const value = translations[lang][key];

        // If translation contains HTML, preserve it
        if (typeof value === "string" && value.includes("<")) {
            el.innerHTML = value;
        } else {
            el.textContent = value;
        }
    });

    // ✅ MudBlazor-safe placeholder handling
    document.querySelectorAll("[data-i18n-placeholder]").forEach(wrapper => {
        const key = wrapper.getAttribute("data-i18n-placeholder");
        const input = wrapper.querySelector("input");

        if (input && translations[lang][key]) {
            input.placeholder = translations[lang][key];
        }
    });
};

window.loadLanguage = () => {
    const lang = localStorage.getItem("lang") || "en";
    window.applyLanguage(lang);
};

window.updateToggleText = (expanded) => {
    const lang = localStorage.getItem("lang") || "en";
    const key = expanded ? "SHOW_LESS" : "READ_MORE";

    document.querySelectorAll("[data-i18n='READ_MORE']").forEach(el => {
        if (translations[lang][key])
            el.innerText = translations[lang][key];
    });
};

